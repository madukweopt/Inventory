CREATE OR REPLACE FUNCTION validate_inventory_dependencies() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
    IF EXISTS(SELECT 1 FROM weighing_requests w WHERE w.status<>'Cancelled' AND w.completed_record_id IS NOT NULL AND (
        (w.request_type='Purchase' AND NOT EXISTS(SELECT 1 FROM purchases p WHERE p.purchase_id=w.completed_record_id)) OR
        (w.request_type='Sale' AND NOT EXISTS(SELECT 1 FROM sales s WHERE s.sales_id=w.completed_record_id)) OR
        (w.request_type='Production' AND NOT EXISTS(SELECT 1 FROM production p WHERE p.production_id=w.completed_record_id)))) THEN
        RAISE EXCEPTION 'A live authorisation cannot reference a deleted business record' USING ERRCODE='23514';
    END IF;
    IF EXISTS(SELECT 1 FROM stock_counts sc JOIN weighing_requests w ON w.request_id=sc.source_id
        WHERE w.status='Cancelled' OR w.completed_record_id IS NULL) THEN
        RAISE EXCEPTION 'Generated stock must belong to a weighed, uncancelled business record' USING ERRCODE='23514';
    END IF;
    RETURN NULL;
END $$;

-- Quality samples only: no stock or financial movements are generated.
CREATE TABLE IF NOT EXISTS kernel_impurity_tests (
    test_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id integer NOT NULL REFERENCES purchases(purchase_id) ON DELETE CASCADE,
    sample_weight_g numeric(15,3) NOT NULL CHECK (sample_weight_g > 0),
    impurity_weight_g numeric(15,3) NOT NULL CHECK (impurity_weight_g >= 0 AND impurity_weight_g <= sample_weight_g),
    recorded_by integer REFERENCES users(user_id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    entry_key uuid NOT NULL,
    UNIQUE (purchase_id,entry_key)
);
CREATE INDEX IF NOT EXISTS kernel_impurity_tests_purchase_idx ON kernel_impurity_tests(purchase_id);

CREATE TABLE IF NOT EXISTS production_batches (
    batch_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id integer NOT NULL REFERENCES weighing_requests(request_id),
    submission_key uuid NOT NULL UNIQUE,
    kernel_used numeric NOT NULL CHECK (kernel_used >= 0),
    pko_produced numeric NOT NULL CHECK (pko_produced >= 0),
    pkc_produced numeric NOT NULL CHECK (pkc_produced >= 0),
    sludge_produced numeric NOT NULL CHECK (sludge_produced >= 0),
    scale_ticket character varying(100),
    recorded_by integer NOT NULL REFERENCES users(user_id),
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (kernel_used + pko_produced + pkc_produced + sludge_produced > 0)
);
CREATE INDEX IF NOT EXISTS production_batches_request_idx ON production_batches(request_id,batch_id);

CREATE UNIQUE INDEX IF NOT EXISTS weighing_requests_daily_production_key ON weighing_requests(request_date) WHERE request_type='Production' AND status IN ('Awaiting Storekeeper','Completed');

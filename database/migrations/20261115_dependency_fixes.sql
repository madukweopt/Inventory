CREATE OR REPLACE FUNCTION expected_payroll_salary(target_employee integer,target_month date) RETURNS numeric LANGUAGE sql STABLE AS $$
    SELECT COALESCE(ROUND(SUM(CASE WHEN COALESCE((SELECT c.status FROM employment_period_changes c
        WHERE c.employee_id=e.employee_id AND c.effective_date<=d::date ORDER BY c.effective_date DESC,c.change_id DESC LIMIT 1),'Active')='Active'
        THEN COALESCE((SELECT h.new_salary FROM salary_history h WHERE h.employee_id=e.employee_id AND h.effective_date<=d::date
            ORDER BY h.effective_date DESC,h.salary_history_id DESC LIMIT 1),
            (SELECT h.new_salary FROM salary_history h WHERE h.employee_id=e.employee_id ORDER BY h.effective_date,h.salary_history_id LIMIT 1),e.salary,0)
            /EXTRACT(day FROM (target_month+INTERVAL '1 month - 1 day')) ELSE 0 END),2),0)
    FROM employees e CROSS JOIN LATERAL generate_series(GREATEST(e.start_date,target_month),
        (target_month+INTERVAL '1 month - 1 day')::date,INTERVAL '1 day') d WHERE e.employee_id=target_employee
$$;

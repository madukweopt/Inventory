-- Director corrections to a sale the driver has signed for: what changed, why and by whom.
CREATE TABLE IF NOT EXISTS sale_corrections (
    correction_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_id integer NOT NULL REFERENCES sales(sales_id) ON DELETE CASCADE,
    reason text NOT NULL,
    previous_values jsonb NOT NULL,
    new_values jsonb NOT NULL,
    corrected_by integer REFERENCES users(user_id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS sale_corrections_sale_idx ON sale_corrections(sales_id);

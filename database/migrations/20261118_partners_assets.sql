-- Other partners: vendors who fabricate, install, supply equipment or repair for the company.
CREATE TABLE IF NOT EXISTS service_partners (
    partner_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL,
    phone_number varchar(30),
    address text,
    email varchar(254),
    work_type text,
    note text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Each job has an agreed price. Capital jobs create an asset; running jobs create an expense for each payment.
CREATE TABLE IF NOT EXISTS partner_jobs (
    job_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_id integer NOT NULL REFERENCES service_partners(partner_id),
    job_date date NOT NULL,
    job_type text NOT NULL CHECK(job_type IN ('Fabrication','Installation','Equipment purchase','Repair','Maintenance/Service','Other')),
    description text NOT NULL,
    agreed_amount numeric(14,2) NOT NULL CHECK(agreed_amount>0),
    cost_category text NOT NULL CHECK(cost_category IN ('Capital','Running')),
    created_by integer REFERENCES users(user_id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS partner_jobs_partner_idx ON partner_jobs(partner_id,job_date);
-- The company's asset register. Capital spending is kept here and never reduces profit.
CREATE TABLE IF NOT EXISTS capital_assets (
    asset_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    asset_type text NOT NULL CHECK(asset_type IN ('Machine','Tank','Building','Vehicle','Electrical','Other')),
    acquired_date date NOT NULL,
    cost numeric(14,2) NOT NULL CHECK(cost>0),
    source text,
    note text,
    job_id integer UNIQUE REFERENCES partner_jobs(job_id) ON DELETE RESTRICT,
    created_by integer REFERENCES users(user_id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Money paid to a partner, recorded by the Director against one job.
CREATE TABLE IF NOT EXISTS partner_payments (
    payment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id integer NOT NULL REFERENCES partner_jobs(job_id) ON DELETE RESTRICT,
    payment_date date NOT NULL,
    amount numeric(14,2) NOT NULL CHECK(amount>0),
    payment_method text NOT NULL,
    reference_number text,
    note text,
    expense_id integer UNIQUE REFERENCES expenses(expense_id) ON DELETE RESTRICT,
    recorded_by integer REFERENCES users(user_id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS partner_payments_job_idx ON partner_payments(job_id);
-- Expenses are now running costs only: move earlier capital entries into the asset register.

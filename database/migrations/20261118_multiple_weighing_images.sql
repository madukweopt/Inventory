-- The first attachment stays in delivery_notes for compatibility with saved notes.
CREATE TABLE IF NOT EXISTS delivery_note_evidence (
    evidence_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_id integer NOT NULL REFERENCES delivery_notes(sales_id) ON DELETE CASCADE,
    content bytea NOT NULL,
    content_type text NOT NULL,
    filename text NOT NULL
);
CREATE INDEX IF NOT EXISTS delivery_note_evidence_sale_idx ON delivery_note_evidence(sales_id);
